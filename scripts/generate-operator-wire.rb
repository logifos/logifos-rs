# frozen_string_literal: true

# Regenerates crates/logifos-model/src/operator_wire.rs from the plurimath
# gem's symbol inventory: each Symbols class's MathML spellings become the
# named-operator identities the wire carries, so Formula::Operator text
# round trips as its plurimath source class.
#
#   ruby scripts/generate-operator-wire.rb PLURIMATH_CHECKOUT
#
# Deterministic: classes sort by name; a MathML spelling claimed by several
# classes encodes as the alphabetically first and the collision is counted.

require "optparse"
require "cgi"

checkout = ARGV.fetch(0) { raise "usage: ruby scripts/generate-operator-wire.rb PLURIMATH_CHECKOUT" }
$LOAD_PATH.unshift(File.join(checkout, "lib"))
require "plurimath"

Plurimath::Math::Symbols.eager_load!
classes = Plurimath::Math::Symbols::Symbol.descendants
  .reject { |klass| klass.name.start_with?("Plurimath::Math::Symbols::Paren::") }
  .sort_by { |klass| klass.name }

by_text = {}
collisions = 0
classes.each do |klass|
  short = klass.name.delete_prefix("Plurimath::")
  spellings = Array(klass::INPUT[:mathml]).filter_map do |entry|
    next unless entry.is_a?(String)

    text = CGI.unescapeHTML(entry)
    text unless text.empty? || text.include?("&")
  end
  spellings.uniq.each do |text|
    if by_text.key?(text)
      collisions += 1
      next
    end
    by_text[text] = short
  end
end

by_text = by_text.sort.to_h
by_class = by_text.map { |text, short| [short, text] }.sort.to_h

def rust_str(value)
  value.chars.map do |char|
    if char.ord < 0x20 || char.ord == 0x7f ||
       format("%c", char.ord) =~ /[\p{Cf}\p{Cc}\p{Co}\p{Cn}]/u
      format("\\u{%x}", char.ord)
    else
      char
    end
  end.join
end

File.open(File.join(__dir__, "../crates/logifos-model/src/operator_wire.rs"), "w") do |file|
  file.puts "// Generated by scripts/generate-operator-wire.rb from the plurimath gem's"
  file.puts "// symbol inventory. Do not edit by hand; regenerate after plurimath's"
  file.puts "// symbol classes change."
  file.puts "//"
  file.puts "// Classes: #{classes.size}; spellings: #{by_text.size}; collisions dropped: #{collisions}."
  file.puts
  file.puts "/// MathML spelling -> the plurimath Symbols class short name, sorted by"
  file.puts "/// spelling for binary search."
  file.puts "pub(crate) static OPERATOR_CLASSES: &[(&str, &str)] = &["
  by_text.each { |text, short| file.puts("    (#{rust_str(text).inspect}, #{rust_str(short).inspect}),") }
  file.puts "];"
  file.puts
  file.puts "/// plurimath Symbols class short name -> MathML spelling, sorted by"
  file.puts "/// class name for binary search."
  file.puts "pub(crate) static OPERATOR_TEXTS: &[(&str, &str)] = &["
  by_class.each { |short, text| file.puts("    (#{rust_str(short).inspect}, #{rust_str(text).inspect}),") }
  file.puts "];"
end
puts "spellings: #{by_text.size}, collisions dropped: #{collisions}"
